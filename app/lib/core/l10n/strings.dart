  /// Looks up [key], substituting `{name}` placeholders from [vars].
  /// Values are Object? rather than Object on purpose: most screens hold the
  /// catalogue in a dynamic, so a literal like {'stage': s.t(...)} infers
  /// `Map<String, dynamic>` and would fail the cast at runtime — a crash no
  /// analyzer can see.
  String t(String key, [Map<String, Object?>? vars]) {
    var s = _m[key] ?? _catalogue[_en]![key] ?? key;
    if (vars != null) {
      vars.forEach((k, v) => s = s.replaceAll('{$k}', '$v'));
    }
    return s;
  }

